    static func matchTones(in text: String) -> [String] {
        var hits: [String] = []
        for (tone, keywords) in tones where keywords.contains(where: { text.contains($0) }) {
            hits.append(tone)
        }
        return hits.sorted()
    }

    /// 收尾（punchline）优先从这些情绪里挑
    static let punchlineTones: Set<String> = ["震惊", "嘲讽", "崩坏", "肯定", "感叹"]

    /// 抽取一段文本命中的主题
    static func matchTopics(in text: String) -> [String] {
        var hits: [String] = []
        for (topic, keywords) in topics where keywords.contains(where: { text.contains($0) }) {
            hits.append(topic)
        }
        return hits.sorted()
    }

    /// 给用户输入做一点口语归一化，提高命中率
    static func normalized(_ text: String) -> String {
        var result = text.trimmingCharacters(in: .whitespacesAndNewlines)
        let replacements: [String: String] = [
            "老美": "美国", "漂亮国": "美国", "米国": "美国",
            "咱们": "中国", "我国": "中国", "天朝": "中国",
